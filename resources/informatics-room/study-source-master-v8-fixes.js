/* 情報Ⅰ source master v8 — 原教材再照合で見つかった細部を追加 */
(() => {
  const master=window.SOURCE_MASTER_V7||{};
  const add=(id,title,body)=>{
    if(!master[id])return;
    if(!master[id].sections.some(x=>x[0]===title))master[id].sections.push([title,body]);
  };
  const terms=(id,values)=>{
    const lesson=(window.STUDY_MAIN||[]).find(x=>x.id===id); if(!lesson)return;
    lesson.terms=[...new Set([...(lesson.terms||[]),...values])];
  };

  add('b1-6','発想を広げる補助手法','ブレーンストーミングを考案したオズボーンは、発想を広げるための「オズボーンのチェックリスト」も考案した。KJ法はブレーンストーミングと組み合わせて使うことができる。アイディアを発散させた後、分類・関連付けによって収束させる流れとして理解する。');
  add('b1-6','特性要因図とロジックツリー','情報や原因をツリー状に整理する代表的な方法として、特性要因図やロジックツリーがある。問題の原因を分解したり、考えを階層化したりするときに使い、ブレーンストーミングやKJ法とは目的の違いを意識する。');
  add('b5-3','論理回路記号とANSI','論理回路の正式な記号には複数の体系がある。原教材で示されている記号はANSI（American National Standards Institute）の体系である。記号の形だけを暗記するより、真理値表からAND・OR・NOTの動作を判断できることを優先する。');
  add('b9-4','独立変数・従属変数の別名','回帰式 Y=aX+b では、Xを独立変数、Yを従属変数とする。独立変数を説明変数、従属変数を目的変数と呼ぶこともある。用語が変わっても、予測に使う側と予測される側の関係で判断する。');
  add('b9-4','単回帰分析と重回帰分析','一つの従属変数を一つの独立変数で予測するものが単回帰分析である。複数の独立変数を使って一つの従属変数を予測するものを重回帰分析という。共通テストでは名称だけでなく、何個の説明変数を使っているかを資料から読めるようにする。');

  terms('b1-6',['オズボーンのチェックリスト','特性要因図','ロジックツリー']);
  terms('b5-3',['ANSI']);
  terms('b9-4',['独立変数','従属変数','説明変数','目的変数','重回帰分析']);
})();